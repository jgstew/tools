#!/usr/bin/env bash
#
# generate_deploy_script.sh
#
# Reads clientsettings.cfg (plain text) and actionsite.afxm (binary) from the
# current directory, and emits a new self-contained script, deploy_bigfix_macos.sh,
# that will recreate both files in whatever directory it's run from -- but
# only if they don't already exist there. Then it will download bigfix macos installer, validate it's sha256, and install it.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
CFG_FILE="${SCRIPT_DIR}/clientsettings.cfg"
AFXM_FILE="${SCRIPT_DIR}/actionsite.afxm"
OUT_FILE="${SCRIPT_DIR}/deploy_bigfix_macos.sh"

PKG_URL="https://software.bigfix.com/download/bes/110/BESAgent-11.0.6.137-BigFix_MacOS11.0.pkg"
PKG_NAME="BESAgent-11.0.6.137-BigFix_MacOS11.0.pkg"
PKG_SHA256="67552d36682ead4586bde9cf9eee435b5cad221437c617196b149f45140a2eac"

for f in "$CFG_FILE" "$AFXM_FILE"; do
    if [[ ! -f "$f" ]]; then
        echo "Error: required input file not found: $f" >&2
        exit 1
    fi
done

{
    printf '%s\n' '#!/usr/bin/env bash'
    printf '%s\n' '#'
    printf '%s\n' '# Auto-generated by generate_deploy_script.sh'
    printf '%s\n' '# Writes clientsettings.cfg and actionsite.afxm into the current directory,'
    printf '%s\n' '# but only if they do not already exist there.'
    printf '\n'
    printf '%s\n' 'set -euo pipefail'
    printf '\n'
    printf '%s\n' '# base64 decode works on both GNU coreutils (base64 -d) and BSD/macOS (base64 -D)'
    printf '%s\n' 'b64decode() {'
    printf '%s\n' '    if base64 --help 2>&1 | grep -q -- "-D"; then'
    printf '%s\n' '        base64 -D'
    printf '%s\n' '    else'
    printf '%s\n' '        base64 -d'
    printf '%s\n' '    fi'
    printf '%s\n' '}'
    printf '\n'
    printf '%s\n' 'if [[ -e clientsettings.cfg ]]; then'
    printf '%s\n' '    echo "clientsettings.cfg already exists, skipping."'
    printf '%s\n' 'else'
    printf '%s\n' "    cat > clientsettings.cfg <<'CLIENTSETTINGS_EOF'"
    cat "$CFG_FILE"
    printf '%s\n' 'CLIENTSETTINGS_EOF'
    printf '%s\n' '    echo "Wrote clientsettings.cfg"'
    printf '%s\n' 'fi'
    printf '\n'
    printf '%s\n' 'if [[ -e actionsite.afxm ]]; then'
    printf '%s\n' '    echo "actionsite.afxm already exists, skipping."'
    printf '%s\n' 'else'
    printf '%s\n' "    b64decode > actionsite.afxm <<'ACTIONSITE_EOF'"
    base64 < "$AFXM_FILE"
    printf '%s\n' 'ACTIONSITE_EOF'
    printf '%s\n' '    echo "Wrote actionsite.afxm"'
    printf '%s\n' 'fi'
    printf '\n'
    printf '%s\n' "PKG_URL='${PKG_URL}'"
    printf '%s\n' "PKG_NAME='${PKG_NAME}'"
    printf '%s\n' "PKG_SHA256='${PKG_SHA256}'"
    printf '\n'
    printf '%s\n' 'if [[ -e "$PKG_NAME" ]]; then'
    printf '%s\n' '    echo "$PKG_NAME already exists, skipping download."'
    printf '%s\n' 'else'
    printf '%s\n' '    echo "Downloading $PKG_NAME ..."'
    printf '%s\n' '    curl -fL -o "$PKG_NAME" "$PKG_URL"'
    printf '%s\n' 'fi'
    printf '\n'
    printf '%s\n' 'echo "Verifying SHA256 checksum of $PKG_NAME ..."'
    printf '%s\n' 'ACTUAL_SHA256="$(shasum -a 256 "$PKG_NAME" | awk '"'"'{print $1}'"'"')"'
    printf '%s\n' 'if [[ "$ACTUAL_SHA256" != "$PKG_SHA256" ]]; then'
    printf '%s\n' '    echo "ERROR: SHA256 mismatch for $PKG_NAME" >&2'
    printf '%s\n' '    echo "  expected: $PKG_SHA256" >&2'
    printf '%s\n' '    echo "  actual:   $ACTUAL_SHA256" >&2'
    printf '%s\n' '    exit 1'
    printf '%s\n' 'else'
    printf '%s\n' '    echo "Checksum OK: $PKG_NAME"'
    printf '%s\n' 'fi'
    printf '\n'
    printf '%s\n' 'echo "Installing $PKG_NAME ..."'
    printf '%s\n' 'sudo installer -pkg "$PKG_NAME" -target / >/dev/null'
} > "$OUT_FILE"

chmod +x "$OUT_FILE"
echo "Generated: $OUT_FILE"
