#!/usr/bin/env python3
"""Generate php_version_branches.yar: one YARA rule per PHP major.minor branch.

For YARA consumers that only report the matching rule *name* (osquery's yara
table, many EDRs) and not the matched text. A hit on PHP_8_2 means the file is
a PHP 8.2.x binary.

Usage:
    python3 gen_php_branches.py > php_version_branches.yar
"""

import datetime
import pathlib
import re

IS_EXECUTABLE_YAR = pathlib.Path(__file__).resolve().parent / "is_executable.yar"

# branch -> ZEND_MODULE_API_NO (the "API2xxxxxxx" build ID / extension dir name).
# Verified against real builds: 5.6, 7.0-7.4, 8.0-8.5 (official Docker images,
# windows.php.net zips, Ubuntu/Rocky packages, conda-forge macOS).
# 5.3-5.5 are from PHP source (main/php.h / Zend/zend_modules.h), not sample-tested.
API_NO = {
    "5.3": "20090626",
    "5.4": "20100525",
    "5.5": "20121212",
    "5.6": "20131226",
    "7.0": "20151012",
    "7.1": "20160303",
    "7.2": "20170718",
    "7.3": "20180731",
    "7.4": "20190902",
    "8.0": "20200930",
    "8.1": "20210902",
    "8.2": "20220829",
    "8.3": "20230831",
    "8.4": "20240924",
    "8.5": "20250925",
}

# Branches with no known API number yet. They still match on the version string;
# anything else falls through to PHP_Branch_Unknown.
FUTURE = ["8.6", "8.7", "9.0", "9.1"]

# Zend Engine version tracks PHP minor: PHP 7.x -> Zend 3.x, PHP 8.x -> Zend 4.x.
# PHP 5.x binaries don't carry the "Zend Engine v" literal, so it is skipped there.
ZEND_MAJOR = {"7": "3", "8": "4"}

HEADER = """/*
  GENERATED by gen_php_branches.py on {date} - edit the generator, not this file.

  One rule per PHP major.minor branch, so the rule NAME is the version
  (PHP_8_2 => PHP 8.2.x). For engines that only report rule names (osquery,
  EDRs). For the exact patch version use php_detect.yar with `yara -s`.

  PHP_Branch_Unknown fires on PHP-looking binaries no branch rule recognised
  (new branch, odd build) - review those and regenerate.

  Rule names here don't collide with php_detect.yar; both files can be loaded together.
*/

// Condition copied from is_executable.yar by sync_rules.py - edit it there
private rule PHP_Branch_IsExecutable
{{
  condition:
{is_executable}
}}
"""

UNKNOWN = """
rule PHP_Branch_Unknown
{{
  meta:
    description = "PHP-looking binary not matched by any branch rule"
  strings:
    $xpb   = "X-Powered-By: PHP/"
    $zend  = "Zend Engine v"
    $api   = /API20[0-9]{{6}},N?TS/
    $pname = {{ 50 00 72 00 6F 00 64 00 75 00 63 00 74 00 4E 00 61 00 6D 00 65 00 [2-4] 50 00 48 00 50 00 00 00 }}
  condition:
    PHP_Branch_IsExecutable and any of them and not (
      {names}
    )
}}
"""


def is_executable_condition():
    """The condition lines of the rule in is_executable.yar (the source of truth)."""
    text = IS_EXECUTABLE_YAR.read_text()
    m = re.search(r"^  condition:\n(.*?)\n\}", text, re.S | re.M)
    if not m:
        raise SystemExit(f"no condition found in {IS_EXECUTABLE_YAR}")
    return m.group(1)


def rule_for(branch):
    major, minor = branch.split(".")
    name = f"PHP_{major}_{minor}"
    strings = [
        f'$xpb = "X-Powered-By: PHP/{branch}."',
        # Windows version resource; wide => UTF-16LE. Only counts together with
        # ProductName=PHP - otherwise e.g. every .NET 7 DLL matches PHP_7_0.
        f'$pv  = "ProductVersion\\x00{branch}." wide',
        "$pname = { 50 00 72 00 6F 00 64 00 75 00 63 00 74 00 4E 00 61 00 6D 00 65 00 [2-4] 50 00 48 00 50 00 00 00 }",
    ]
    markers = ["$xpb"]
    if major in ZEND_MAJOR:
        strings.append(f'$zend = "Zend Engine v{ZEND_MAJOR[major]}.{minor}."')
        markers.append("$zend")
    if branch in API_NO:
        strings.append(f'$api = "API{API_NO[branch]},"')
        markers.append("$api")
    markers.append("($pv and $pname)")
    body = "\n    ".join(strings)
    condition = " or ".join(markers)
    rule = """
rule {name}
{{
  meta:
    php_branch = "{branch}"
  strings:
    {body}
  condition:
    PHP_Branch_IsExecutable and ({condition})
}}
""".format(
        name=name, branch=branch, body=body, condition=condition
    )
    return name, rule


def generate():
    """The full text of php_version_branches.yar."""
    branches = list(API_NO) + FUTURE
    out = [
        HEADER.format(
            date=datetime.date.today().isoformat(),
            is_executable=is_executable_condition(),
        )
    ]
    names = []
    for b in branches:
        name, rule = rule_for(b)
        names.append(name)
        out.append(rule)
    out.append(UNKNOWN.format(names=" or\n      ".join(names)))
    return "".join(out)


def main():
    print(generate(), end="")


if __name__ == "__main__":
    main()
